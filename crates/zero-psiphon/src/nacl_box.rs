//! NaCl's `box`: X25519 with XSalsa20-Poly1305.
//!
//! Psiphon encrypts two things with NaCl's `crypto_box`: the meek cookie, which
//! every relay-mode request carries in an HTTP cookie, and the tactics
//! request/response payloads. Both are `box.Seal` from Go's
//! `golang.org/x/crypto/nacl/box`, so both need exactly this construction:
//!
//! ```text
//! shared    = X25519(sender_secret, recipient_public)
//! subkey    = HSalsa20(shared, 0^16)
//! (tag, ct) = XSalsa20-Poly1305(subkey, nonce, plaintext)
//! ```
//!
//! The Rust ecosystem offers this as `crypto_box`, which is not in this
//! workspace's dependency set. The construction is a composition of three
//! primitives that are — `x25519-dalek`, `salsa20` and `poly1305` — and each
//! layer here is checked against vectors generated by Go's own implementation
//! (`nacl/box`, `nacl/secretbox`, `salsa20/salsa`); see the tests. Nothing in
//! this file invents a construction: it assembles a published one.
//!
//! This is not a general-purpose crypto module and is deliberately not public.
//! It exists so Psiphon's framing can be reproduced byte for byte.

use poly1305::universal_hash::KeyInit;
use poly1305::Poly1305;
use salsa20::cipher::{Array, KeyIvInit, StreamCipher};
use salsa20::hsalsa;
use salsa20::Salsa20;

/// NaCl's `box` overhead: the Poly1305 tag.
pub const BOX_OVERHEAD: usize = 16;
/// The nonce length both `box` and `secretbox` take.
pub const NONCE_LENGTH: usize = 24;
/// The key length.
pub const KEY_LENGTH: usize = 32;

/// The key a `box` derives from a key agreement, as `crypto_box_beforenm`
/// does: HSalsa20 over the raw X25519 output with a zero nonce.
pub fn before_nm(shared_secret: &[u8; KEY_LENGTH]) -> [u8; KEY_LENGTH] {
    let zero_nonce = Array::default();
    hsalsa::<salsa20::cipher::consts::U10>(shared_secret.into(), &zero_nonce).into()
}

/// The shared secret between `secret` and `peer_public`.
///
/// The result is not checked for the all-zero output, because NaCl's `box`
/// does not check it either: a peer that supplied a low-order point has not
/// proven anything, and the caller is authenticating with the SSH host key
/// regardless. Callers that need the check should do it where they can act on
/// it.
pub fn shared_secret(
    secret: &[u8; KEY_LENGTH],
    peer_public: &[u8; KEY_LENGTH],
) -> [u8; KEY_LENGTH] {
    x25519_dalek::x25519(*secret, *peer_public)
}

/// The X25519 public key for `secret`.
pub fn public_key(secret: &[u8; KEY_LENGTH]) -> [u8; KEY_LENGTH] {
    x25519_dalek::PublicKey::from(&x25519_dalek::StaticSecret::from(*secret)).to_bytes()
}

/// XSalsa20-Poly1305, equivalent to NaCl's `secretbox.Seal`: the tag followed
/// by the ciphertext.
pub fn secretbox_seal(
    key: &[u8; KEY_LENGTH],
    nonce: &[u8; NONCE_LENGTH],
    plaintext: &[u8],
) -> Vec<u8> {
    let mut cipher = xsalsa20(key, nonce);

    // The first 32 bytes of the keystream are the one-time Poly1305 key; the
    // message's is everything after them, so the cipher must be advanced
    // before the plaintext is XORed.
    let mut poly_key = [0u8; 32];
    cipher.apply_keystream(&mut poly_key);

    let mut ciphertext = plaintext.to_vec();
    cipher.apply_keystream(&mut ciphertext);

    let mut poly_key_array = Array::default();
    poly_key_array.copy_from_slice(&poly_key);
    let tag = Poly1305::new(&poly_key_array).compute_unpadded(&ciphertext);

    let mut out = Vec::with_capacity(BOX_OVERHEAD + ciphertext.len());
    out.extend_from_slice(tag.as_slice());
    out.extend_from_slice(&ciphertext);
    out
}

/// The inverse of [`secretbox_seal`]. Returns `None` when the tag does not
/// match, which is the only failure it reports: the tag covers every byte the
/// caller supplied.
pub fn secretbox_open(
    key: &[u8; KEY_LENGTH],
    nonce: &[u8; NONCE_LENGTH],
    boxed: &[u8],
) -> Option<Vec<u8>> {
    if boxed.len() < BOX_OVERHEAD {
        return None;
    }
    let (tag, ciphertext) = boxed.split_at(BOX_OVERHEAD);

    let mut cipher = xsalsa20(key, nonce);
    let mut poly_key = [0u8; 32];
    cipher.apply_keystream(&mut poly_key);

    // Verify before decrypting, so a forged message is never handed to the
    // caller even for an instant.
    let mut poly_key_array = Array::default();
    poly_key_array.copy_from_slice(&poly_key);
    let expected = Poly1305::new(&poly_key_array).compute_unpadded(ciphertext);
    if !constant_time_eq(tag, expected.as_slice()) {
        return None;
    }

    let mut plaintext = ciphertext.to_vec();
    cipher.apply_keystream(&mut plaintext);
    Some(plaintext)
}

/// NaCl's `box.Seal`: the key agreement, then `secretbox`.
pub fn seal(
    nonce: &[u8; NONCE_LENGTH],
    plaintext: &[u8],
    peer_public: &[u8; KEY_LENGTH],
    secret: &[u8; KEY_LENGTH],
) -> Vec<u8> {
    let key = before_nm(&shared_secret(secret, peer_public));
    secretbox_seal(&key, nonce, plaintext)
}

/// NaCl's `box.Open`.
pub fn open(
    nonce: &[u8; NONCE_LENGTH],
    boxed: &[u8],
    peer_public: &[u8; KEY_LENGTH],
    secret: &[u8; KEY_LENGTH],
) -> Option<Vec<u8>> {
    let key = before_nm(&shared_secret(secret, peer_public));
    secretbox_open(&key, nonce, boxed)
}

/// The XSalsa20 stream `secretbox` is built on: HSalsa20 over the first 16
/// nonce bytes gives the subkey, the last 8 bytes are Salsa20's nonce.
fn xsalsa20(key: &[u8; KEY_LENGTH], nonce: &[u8; NONCE_LENGTH]) -> Salsa20 {
    // Splitting the nonce is the whole of XSalsa20: its first 16 bytes go
    // through HSalsa20 to make a subkey, its last 8 are Salsa20's nonce.
    let (first, second) = nonce.split_at(16);
    let mut first_16 = Array::default();
    first_16.copy_from_slice(first);
    let subkey: [u8; 32] = hsalsa::<salsa20::cipher::consts::U10>(key.into(), &first_16).into();

    let mut last_8 = Array::default();
    last_8.copy_from_slice(second);
    Salsa20::new(&subkey.into(), &last_8)
}

/// A comparison whose timing does not depend on where the first difference is.
fn constant_time_eq(left: &[u8], right: &[u8]) -> bool {
    if left.len() != right.len() {
        return false;
    }
    let mut difference = 0u8;
    for (a, b) in left.iter().zip(right) {
        difference |= a ^ b;
    }
    difference == 0
}

#[cfg(test)]
mod tests {
    use super::*;

    // Generated by `.research/wire-vectors/go/boxvec` (Go's `nacl/box`,
    // `nacl/secretbox` and `salsa20/salsa`) so each layer is checked against
    // the implementation Psiphon actually uses.
    const ALICE_PRIVATE: &str = "0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20";
    const ALICE_PUBLIC: &str = "07a37cbc142093c8b755dc1b10e86cb426374ad16aa853ed0bdfc0b2b86d1c7c";
    const BOB_PRIVATE: &str = "404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f";
    const BOB_PUBLIC: &str = "79a631eede1bf9c98f12032cdeadd0e7a079398fc786b88cc846ec89af85a51a";
    const SHARED: &str = "ae4440cc8d7faddb2894172b78e3d745cafa0098bcc10d7ee0fda08fa85a9a2e";
    const SUBKEY: &str = "9e37e3406bf2f4e3027022945e0f1e159739ceae2cca4d45aa3592ea30e07183";
    const NONCE: &str = "a0a1a2a3a4a5a6a7a8a9aaabacadaeafb0b1b2b3b4b5b6b7";
    const MESSAGE: &[u8] = b"psiphon-meek-cookie-vector";
    const SECRETBOX: &str =
        "e63c3ef5c676a4c0c480c84ebabeb3f9c5bc3c6c3487d28b91ccb85a3845fe31f4d9c61dd6f37d22415f";
    const BOX_ZERO_NONCE: &str =
        "7b302fe43557bb557a6f9e2e571a5bce8caa1349f073bd4c9fce58f3a3df9fbd3fc727b992371eefbd90";

    fn key(hex_text: &str) -> [u8; 32] {
        hex::decode(hex_text).unwrap().try_into().unwrap()
    }

    fn nonce(hex_text: &str) -> [u8; 24] {
        hex::decode(hex_text).unwrap().try_into().unwrap()
    }

    #[test]
    fn key_agreement_matches_go() {
        let alice_private = key(ALICE_PRIVATE);
        let bob_private = key(BOB_PRIVATE);
        assert_eq!(hex::encode(public_key(&alice_private)), ALICE_PUBLIC);
        assert_eq!(hex::encode(public_key(&bob_private)), BOB_PUBLIC);
        assert_eq!(
            hex::encode(shared_secret(&alice_private, &key(BOB_PUBLIC))),
            SHARED
        );
        // The agreement is symmetric, as both ends need it to be.
        assert_eq!(
            hex::encode(shared_secret(&bob_private, &key(ALICE_PUBLIC))),
            SHARED
        );
    }

    #[test]
    fn before_nm_matches_go() {
        assert_eq!(hex::encode(before_nm(&key(SHARED))), SUBKEY);
    }

    #[test]
    fn secretbox_matches_go() {
        let sealed = secretbox_seal(&key(SUBKEY), &nonce(NONCE), MESSAGE);
        assert_eq!(hex::encode(&sealed), SECRETBOX);
        assert_eq!(
            secretbox_open(&key(SUBKEY), &nonce(NONCE), &sealed).unwrap(),
            MESSAGE
        );
    }

    #[test]
    fn box_matches_go() {
        let boxed = seal(
            &nonce(NONCE),
            MESSAGE,
            &key(BOB_PUBLIC),
            &key(ALICE_PRIVATE),
        );
        // Go's `box.Seal` with the same inputs produces the same bytes: the
        // derived key makes box and secretbox agree.
        assert_eq!(hex::encode(&boxed), SECRETBOX);
        assert_eq!(
            open(&nonce(NONCE), &boxed, &key(ALICE_PUBLIC), &key(BOB_PRIVATE)).unwrap(),
            MESSAGE
        );

        // The zero nonce, which is what the meek cookie uses.
        let boxed = seal(&[0u8; 24], MESSAGE, &key(BOB_PUBLIC), &key(ALICE_PRIVATE));
        assert_eq!(hex::encode(&boxed), BOX_ZERO_NONCE);
        assert_eq!(
            open(&[0u8; 24], &boxed, &key(ALICE_PUBLIC), &key(BOB_PRIVATE)).unwrap(),
            MESSAGE
        );
    }

    #[test]
    fn a_tampered_or_truncated_box_does_not_open() {
        let boxed = seal(
            &nonce(NONCE),
            MESSAGE,
            &key(BOB_PUBLIC),
            &key(ALICE_PRIVATE),
        );

        for index in [0, 15, 16, boxed.len() - 1] {
            let mut edited = boxed.clone();
            edited[index] ^= 1;
            assert!(
                open(
                    &nonce(NONCE),
                    &edited,
                    &key(ALICE_PUBLIC),
                    &key(BOB_PRIVATE)
                )
                .is_none(),
                "a flipped bit at {index} must not open"
            );
        }

        assert!(open(
            &nonce(NONCE),
            &boxed[..15],
            &key(ALICE_PUBLIC),
            &key(BOB_PRIVATE)
        )
        .is_none());

        // The wrong recipient cannot read it either.
        assert!(open(&nonce(NONCE), &boxed, &key(BOB_PUBLIC), &key(BOB_PRIVATE)).is_none());
    }

    #[test]
    fn empty_payloads_round_trip() {
        // A tactics request can be an empty JSON object, and a padding header
        // can be an empty body; neither may be rejected for being short.
        let key = key(SUBKEY);
        let sealed = secretbox_seal(&key, &nonce(NONCE), b"");
        assert_eq!(sealed.len(), BOX_OVERHEAD);
        assert_eq!(
            secretbox_open(&key, &nonce(NONCE), &sealed).unwrap(),
            Vec::<u8>::new()
        );
    }
}
